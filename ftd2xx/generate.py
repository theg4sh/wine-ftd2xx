#!/usr/bin/env python3
import argparse
import json
import re
import shutil
from pathlib import Path

SCALARS = {
    "BOOL": "INT32",
    "DWORD": "UINT32",
    "FT_DEVICE": "UINT32",
    "FT_STATUS": "UINT32",
    "ULONG": "UINT32",
    "USHORT": "UINT16",
    "WORD": "UINT16",
    "UCHAR": "UINT8",
    "int": "INT32",
}

POINTER_TYPES = {
    "HANDLE", "LPCSTR", "LPCTSTR", "LPDWORD", "LPFTCOMSTAT", "LPFTDCB", "LPLONG",
    "LPOVERLAPPED", "LPSECURITY_ATTRIBUTES", "LPVOID", "LPWORD", "PCHAR",
    "PFT_PROGRAM_DATA", "PUCHAR", "PULONG", "PVOID",
}


def parse_arg(text):
    match = re.match(r"^(.+?)\s*([A-Za-z_]\w*)$", text.strip())
    if not match:
        raise ValueError(f"Cannot parse argument: {text}")
    ctype, name = match.groups()
    ctype = ctype.strip()
    if ctype == "FT_HANDLE":
        kind = "handle"
    elif "*" in ctype or ctype in POINTER_TYPES:
        kind = "pointer"
    elif ctype in SCALARS:
        kind = "scalar"
    else:
        raise ValueError(f"Unknown scalar type {ctype!r} in {text!r}")
    return {"type": ctype, "name": name, "kind": kind}


def shared_type(export, arg):
    override = export.get("shared_overrides", {}).get(arg["name"])
    if override:
        return override
    if arg["kind"] == "handle":
        return "UINT32"
    if arg["kind"] == "pointer":
        if arg["type"] == "FT_HANDLE *":
            return "UINT32 *"
        return arg["type"]
    return SCALARS[arg["type"]]


def field(arg, ctype=None):
    return f"{ctype or shared_type_current(arg)} {arg['name']}"


def shared_type_current(arg):
    return arg["_shared_type"]


def prepare(exports):
    for export in exports:
        export["parsed_args"] = [parse_arg(arg) for arg in export["args"]]
        for arg in export["parsed_args"]:
            arg["_shared_type"] = shared_type(export, arg)
    return exports


def params_fields(export, wow64=False):
    fields = []
    for arg in export["parsed_args"]:
        ctype = arg["_shared_type"]
        if wow64 and arg["kind"] == "pointer":
            ctype = "PTR32"
        fields.append(f"    {ctype} {arg['name']};")
    fields.extend(f"    {line};" for line in export.get("extra_shared", []))
    if export["return"] != "void":
        fields.append("    UINT32 result;")
    return "\n".join(fields)


def generate_header(exports, prelude):
    out = [prelude]
    for export in exports:
        if export["impl"] == "stub":
            continue
        out.append(f"struct {export['name']}_params\n{{\n{params_fields(export)}\n}};\n")
    out.append("enum ftd2xx_unix_funcs\n{\n    unix_attach,\n    unix_detach,\n    unix_event_wait,\n    unix_event_stop,\n    unix_event_destroy,")
    out.extend(f"    unix_{export['name']}," for export in exports if export["impl"] != "stub")
    out.append("    unix_funcs_count\n};\n")
    out.append("#endif /* __FTD2XX_UNIXLIB_H */\n")
    return "\n".join(out)


def generate_spec(exports):
    lines = ["# Generated by ftd2xx/generate.py; edit api.json instead."]
    for export in exports:
        if export["impl"] == "stub":
            lines.append(f"{export['ordinal']} stub {export['name']}")
            continue
        args = []
        for arg in export["parsed_args"]:
            args.append("ptr" if arg["kind"] in ("handle", "pointer") else "long")
        lines.append(f"{export['ordinal']} stdcall {export['name']}({' '.join(args)})")
    return "\n".join(lines) + "\n"


def pe_arg(arg):
    return f"{arg['type']} {arg['name']}"


def pe_value(arg):
    return f"PtrToUlong({arg['name']})" if arg["kind"] == "handle" else arg["name"]


def unsupported_value(export):
    if export["return"] == "FT_STATUS":
        return "FT_NOT_SUPPORTED"
    if export["return"] == "BOOL":
        return "FALSE"
    if export["return"] == "DWORD":
        return "ERROR_NOT_SUPPORTED"
    if export["return"] == "FT_HANDLE":
        return "(FT_HANDLE)INVALID_HANDLE_VALUE"
    raise ValueError(f"No unsupported return value for {export['name']}")


def generate_pe(exports, prelude, custom):
    out = [prelude]
    for export in exports:
        if export["impl"] in ("stub", "custom"):
            continue
        args = ", ".join(pe_arg(arg) for arg in export["parsed_args"])
        out.append(f"{export['return']} WINAPI {export['name']}({args or 'void'})\n{{")
        if export["impl"] == "unsupported":
            out.append(f"    return {unsupported_value(export)};\n}}\n")
            continue
        out.append(f"    struct {export['name']}_params params = {{0}};")
        for arg in export["parsed_args"]:
            out.append(f"    params.{arg['name']} = {pe_value(arg)};")
        out.append("    params.result = FT_OTHER_ERROR;")
        out.append(f"    UNIX_CALL({export['name']}, &params);")
        out.append("    return params.result;\n}\n")
    out.append(custom)
    return "\n".join(out)


def native_prototype(export):
    args = ", ".join(pe_arg(arg) for arg in export["parsed_args"])
    return f"static {export['return']} (*p{export['name']})({args or 'void'});"


def native_value(arg):
    return f"handle->native" if arg["kind"] == "handle" else f"params->{arg['name']}"


def generate_native_wrapper(export):
    name = export["name"]
    args = export["parsed_args"]
    has_handle = any(arg["kind"] == "handle" for arg in args)
    out = [f"static NTSTATUS wrap_{name}(void *args)\n{{",
           f"    struct {name}_params *params = args;"]
    if has_handle:
        out.append("    struct ft_handle_entry *handle;")
    out.append(f"    if (!p{name})\n    {{\n        params->result = FT_NOT_SUPPORTED;\n        return STATUS_SUCCESS;\n    }}")
    if has_handle:
        out.append("    handle = handle_acquire(params->ftHandle);")
        out.append("    if (!handle)\n    {\n        params->result = FT_INVALID_HANDLE;\n        return STATUS_SUCCESS;\n    }")
    call_args = ", ".join(native_value(arg) for arg in args)
    out.append(f"    params->result = p{name}({call_args});")
    if has_handle:
        out.append("    handle_release(handle);")
    out.append("    return STATUS_SUCCESS;\n}\n")
    return "\n".join(out)


def generate_wow64_wrapper(export):
    name = export["name"]
    out = [f"static NTSTATUS wow64_{name}(void *args)\n{{",
           "    struct\n    {",
           params_fields(export, wow64=True),
           f"    }} *params32 = args;",
           f"    struct {name}_params params = {{0}};"]
    for arg in export["parsed_args"]:
        if arg["kind"] == "pointer":
            value = f"ULongToPtr(params32->{arg['name']})"
        else:
            value = f"params32->{arg['name']}"
        out.append(f"    params.{arg['name']} = {value};")
    for extra in export.get("extra_shared", []):
        field_name = extra.rsplit(" ", 1)[1]
        out.append(f"    params.{field_name} = params32->{field_name};")
    out.append(f"    wrap_{name}(&params);")
    out.append("    params32->result = params.result;")
    out.append("    return STATUS_SUCCESS;\n}\n")
    return "\n".join(out)


def generate_native(exports, prelude, custom):
    out = [prelude]
    out.extend(native_prototype(export) for export in exports if export["impl"] in ("simple", "custom"))
    out.append("static void *ftd2xx_handle;\n")
    out.append("#define LOAD_REQUIRED(name) do { \\\n    if (!(p##name = dlsym(ftd2xx_handle, #name))) goto fail; \\\n} while (0)\n")
    out.append("#define LOAD_OPTIONAL(name) p##name = dlsym(ftd2xx_handle, #name)\n")
    out.append("static NTSTATUS attach(void *args)\n{\n    const char *libname = args;\n")
    out.append("    ftd2xx_handle = dlopen(libname, RTLD_NOW);\n    if (!ftd2xx_handle) return STATUS_DLL_NOT_FOUND;\n")
    for export in exports:
        if export["impl"] not in ("simple", "custom"):
            continue
        macro = "LOAD_REQUIRED" if export.get("required") else "LOAD_OPTIONAL"
        out.append(f"    {macro}({export['name']});")
    out.append("    return STATUS_SUCCESS;\nfail:\n    dlclose(ftd2xx_handle);\n    ftd2xx_handle = NULL;\n    return STATUS_ENTRYPOINT_NOT_FOUND;\n}\n")
    out.append("static NTSTATUS detach(void *args)\n{\n    custom_detach();\n    if (ftd2xx_handle) dlclose(ftd2xx_handle);\n    ftd2xx_handle = NULL;\n    return STATUS_SUCCESS;\n}\n")
    out.append("static NTSTATUS wrap_unsupported(void *args)\n{\n    return STATUS_SUCCESS;\n}\n")
    out.append(custom)
    out.extend(generate_native_wrapper(export) for export in exports if export["impl"] == "simple")
    out.append("#ifdef _WIN64\ntypedef ULONG PTR32;\n")
    out.extend(generate_wow64_wrapper(export) for export in exports
               if export["impl"] in ("simple", "custom") and
               any(arg["kind"] == "pointer" for arg in export["parsed_args"]))
    out.append("#endif /* _WIN64 */\n")
    out.append("#define UCALL(name) [unix_##name] = wrap_##name\n")
    out.append("const unixlib_entry_t __wine_unix_call_funcs[] =\n{\n    [unix_attach] = attach,\n    [unix_detach] = detach,\n    [unix_event_wait] = wrap_event_wait,\n    [unix_event_stop] = wrap_event_stop,\n    [unix_event_destroy] = wrap_event_destroy,")
    for export in exports:
        if export["impl"] == "stub":
            continue
        if export["impl"] == "unsupported":
            out.append(f"    [unix_{export['name']}] = wrap_unsupported,")
        else:
            out.append(f"    UCALL({export['name']}),")
    out.append("};\nC_ASSERT(ARRAYSIZE(__wine_unix_call_funcs) == unix_funcs_count);\n")
    out.append("#ifdef _WIN64\nconst unixlib_entry_t __wine_unix_call_wow64_funcs[] =\n{\n    [unix_attach] = attach,\n    [unix_detach] = detach,\n    [unix_event_wait] = wrap_event_wait,\n    [unix_event_stop] = wrap_event_stop,\n    [unix_event_destroy] = wrap_event_destroy,")
    for export in exports:
        if export["impl"] == "stub":
            continue
        if export["impl"] == "unsupported":
            target = "wrap_unsupported"
        elif any(arg["kind"] == "pointer" for arg in export["parsed_args"]):
            target = f"wow64_{export['name']}"
        else:
            target = f"wrap_{export['name']}"
        out.append(f"    [unix_{export['name']}] = {target},")
    out.append("};\nC_ASSERT(ARRAYSIZE(__wine_unix_call_wow64_funcs) == unix_funcs_count);\n#endif /* _WIN64 */\n")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description="Generate the Wine PE/Unix FTD2XX wrapper")
    parser.add_argument("--source", type=Path, default=Path(__file__).resolve().parent)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    source = args.source.resolve()
    output = args.output.resolve()
    exports = prepare(json.loads((source / "api.json").read_text()))
    output.mkdir(parents=True, exist_ok=True)

    (output / "ftd2xx.spec").write_text(generate_spec(exports))
    (output / "unixlib.h").write_text(generate_header(exports, (source / "shared_prelude.h").read_text()))
    (output / "ftd2xx.c").write_text(generate_pe(
        exports, (source / "pe_prelude.c").read_text(), (source / "pe_custom.c").read_text()))
    (output / "unixlib.c").write_text(generate_native(
        exports, (source / "unix_prelude.c").read_text(), (source / "unix_custom.c").read_text()))
    shutil.copyfile(source / "Makefile.in", output / "Makefile.in")
    (output / ".generated-by").write_text("ftd2xx/generate.py; do not edit generated files directly\n")


if __name__ == "__main__":
    main()
